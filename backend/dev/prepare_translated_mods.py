# -*- coding: utf-8 -*-
"""Desktop preparation: read JAR metadata in place and produce a Python runtime index."""
import argparse
import hashlib
import json
from pathlib import Path
import tomllib
import zipfile


def prepare(config_path):
    config_path = Path(config_path).resolve()
    config = json.loads(config_path.read_text(encoding="utf-8-sig"))
    rows = []
    seen = set()
    for binding in config["bindings"]:
        jar = Path(binding["source_jar"])
        if not jar.is_absolute():
            jar = config_path.parent / jar
        jar = jar.resolve(strict=True)
        with zipfile.ZipFile(jar) as archive:
            metadata = tomllib.loads(archive.read("META-INF/neoforge.mods.toml").decode("utf-8-sig"))
        declared = {mod["modId"]: mod for mod in metadata.get("mods", [])}
        entries = binding["entrypoints"]
        if set(entries) != set(declared):
            raise ValueError("Provide an entrypoint for every declared mod in " + str(jar))
        digest = hashlib.sha256(jar.read_bytes()).hexdigest()
        for mod_id, entrypoint in sorted(entries.items()):
            if mod_id in seen:
                raise ValueError("Duplicate mod ID: " + mod_id)
            seen.add(mod_id)
            required = []
            constraints = []
            for dep in metadata.get("dependencies", {}).get(mod_id, []):
                kind = dep.get("type", "required" if dep.get("mandatory", True) else "optional")
                constraints.append(dict(dep))
                # Runtime interprets dependency side, ordering and type together.
            rows.append({
                "mod_id": mod_id, "version": declared[mod_id].get("version", ""),
                "entrypoint": entrypoint, "requires": required,
                "side": binding.get("side", "BOTH"),
                "dependency_constraints": constraints,
                "source_jar": str(jar), "source_sha256": digest,
            })
    return {"schema_version": 1, "mods": rows,
            "platform_versions": config.get("platform_versions", {})}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("config", help="JSON bindings file; JAR paths are relative to this file")
    parser.add_argument("output", help="Generated Python index file")
    args = parser.parse_args()
    index = prepare(args.config)
    payload = json.dumps(index, ensure_ascii=True, sort_keys=True)
    source = "# -*- coding: utf-8 -*-\n# Generated by dev/prepare_translated_mods.py\nimport json\nMOD_INDEX = json.loads(" + repr(payload) + ")\n"
    Path(args.output).write_text(source, encoding="utf-8")
    print("Prepared %d mods; source JARs unchanged." % len(index["mods"]))


if __name__ == "__main__":
    main()
