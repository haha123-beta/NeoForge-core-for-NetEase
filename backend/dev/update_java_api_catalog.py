from workspace_paths import SCRIPTS_ROOT as _PROJECT_SCRIPTS
"""Regenerate the static runtime Java API module catalog after adding mappings."""
from pathlib import Path
import re


def catalog(root):
    modules = []
    for path in sorted(Path(root).rglob('*.py')):
        relative = path.relative_to(root)
        if relative.parts[0] in ('core', 'launcher_skip', 'container'):
            continue
        if not re.search(r'^JAVA_MAP\s*=', path.read_text(encoding='utf-8-sig'), re.M):
            continue
        name = '.'.join(relative.with_suffix('').parts)
        if name.endswith('.__init__'):
            name = name[:-9]
        modules.append(name)
    return tuple(modules)


if __name__ == '__main__':
    root = Path(_PROJECT_SCRIPTS)
    text = '# -*- coding: utf-8 -*-\n# Generated by dev/update_java_api_catalog.py.\nAPI_MODULES = (\n'
    text += ''.join('    ' + repr(name) + ',\n' for name in catalog(root)) + ')\n'
    (root / 'core/java_api_catalog.py').write_text(text, encoding='utf-8')
